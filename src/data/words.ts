export function wordsForGrade(grade: Grade): WordEntry[] {
  return WORD_LISTS[grade] ?? []
}

/** Lowercases and strips accents, so "pinata" matches "pi\u00f1ata". */
export function normalizeWord(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}

export function matchesWord(entry: WordEntry, attempt: string): boolean {
  const given = normalizeWord(attempt)
  if (!given) return false
  return [entry.word, ...(entry.accepts ?? [])].some((w) => normalizeWord(w) === given)
}
